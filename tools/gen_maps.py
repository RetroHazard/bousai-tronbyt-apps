#!/usr/bin/env python3
"""Regenerate src/lib/bousai_mapdata.star: embedded land bitmaps for overview maps.

Land polygons: Natural Earth 1:10m land (public domain),
https://github.com/nvkelso/natural-earth-vector

Bitmaps are Web Mercator crops at a fixed zoom so apps can place markers with
the same projection the JMA tile layers use. Land is mid-grey with
anti-aliased alpha; apps tint it with filter.Brightness for the active theme.

Usage: uv run --with pillow tools/gen_maps.py
"""

import base64
import io
import json
import math
import urllib.request
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "lib" / "bousai_mapdata.star"
LAND_URL = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_land.geojson"
SUPERSAMPLE = 4

# name: (zoom, west, south, east, north)
MAPS = {
    "japan": (4, 120.0, 20.0, 155.0, 47.0),
    "pacific": (2, 95.0, -5.0, 180.0, 60.0),
}


def world_px(lat: float, lon: float, zoom: int) -> tuple:
    size = 256 * (2 ** zoom)
    x = (lon + 180.0) / 360.0 * size
    r = math.radians(lat)
    y = (1.0 - math.log(math.tan(r) + 1.0 / math.cos(r)) / math.pi) / 2.0 * size
    return x, y


def rings(geometry: dict):
    if geometry["type"] == "Polygon":
        yield from geometry["coordinates"]
    elif geometry["type"] == "MultiPolygon":
        for poly in geometry["coordinates"]:
            yield from poly


def render(features: list, zoom: int, west: float, south: float, east: float, north: float) -> tuple:
    x0, y0 = world_px(north, west, zoom)
    x1, y1 = world_px(south, east, zoom)
    width, height = round(x1 - x0), round(y1 - y0)
    mask = Image.new("L", (width * SUPERSAMPLE, height * SUPERSAMPLE), 0)
    draw = ImageDraw.Draw(mask)
    for feature in features:
        for ring in rings(feature["geometry"]):
            lons = [p[0] for p in ring]
            if max(lons) < west - 5 or min(lons) > east + 5:
                continue
            pts = []
            for lon, lat in ring:
                lat = max(-85.0, min(85.0, lat))
                x, y = world_px(lat, lon, zoom)
                pts.append(((x - x0) * SUPERSAMPLE, (y - y0) * SUPERSAMPLE))
            if len(pts) >= 3:
                draw.polygon(pts, fill=255)
    alpha = mask.resize((width, height), Image.BOX)
    img = Image.new("RGBA", (width, height), (128, 128, 128, 0))
    img.putalpha(alpha)
    buf = io.BytesIO()
    img.save(buf, "PNG", optimize=True)
    return width, height, round(x0), round(y0), buf.getvalue()


def main() -> None:
    with urllib.request.urlopen(LAND_URL, timeout=300) as resp:
        features = json.load(resp)["features"]
    lines = [
        '"""Embedded land bitmaps (Natural Earth 1:10m, public domain). GENERATED by tools/gen_maps.py; do not edit."""',
        "",
        "# name -> {zoom, x0, y0 (Web Mercator world-pixel origin), w, h, png (base64)}",
        "BOUSAI_BASEMAPS = {",
    ]
    for name, (zoom, west, south, east, north) in MAPS.items():
        width, height, x0, y0, png = render(features, zoom, west, south, east, north)
        lines.append(f'    "{name}": {{')
        lines.append(f'        "zoom": {zoom},')
        lines.append(f'        "x0": {x0},')
        lines.append(f'        "y0": {y0},')
        lines.append(f'        "w": {width},')
        lines.append(f'        "h": {height},')
        lines.append(f'        "png": "{base64.b64encode(png).decode()}",')
        lines.append("    },")
        print(f"{name}: {width}x{height} at z{zoom}, {len(png)} bytes")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
